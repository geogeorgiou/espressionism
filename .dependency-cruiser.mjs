/**
 * Import boundaries between the workspace packages and inside the client.
 * Run with `pnpm lint:boundaries`; CI only, to keep the pre-commit hook fast.
 *
 * Layer rules apply to source files; tests may reach across them to build
 * fixtures, but still have to resolve and stay acyclic.
 *
 * @type {import('dependency-cruiser').IConfiguration}
 */

const TESTS = '(^packages/[^/]+/test/|\\.test\\.tsx?$)'
const CLIENT = '^packages/client/src/'
const BASE_FEATURES = '(mascot|theme|common|webmcp)'
const DOMAIN_FEATURES = '(calculator|store|chat)'

/** A layer rule: ignores tests on the importing side. */
const layer = (rule) => ({
  severity: 'error',
  ...rule,
  from: { ...rule.from, pathNot: [rule.from.pathNot, TESTS].filter(Boolean) },
})

export default {
  forbidden: [
    // Hygiene
    {
      name: 'no-circular',
      severity: 'error',
      comment:
        'Cycles make modules impossible to understand or test on their own. Break the cycle by moving the shared piece down a layer (for a route, read it with getRouteApi instead of importing Route).',
      from: {},
      to: {
        circular: true,
        // Generated by TanStack Router: registers the router's type with a
        // type-only import back to router.tsx. Not ours to break.
        viaNot: '^packages/client/src/routeTree\\.gen\\.ts$',
      },
    },
    {
      name: 'not-to-unresolvable',
      severity: 'error',
      comment:
        "This import doesn't resolve to a file. Fix the path, or add the package to package.json.",
      from: {},
      to: { couldNotResolve: true },
    },
    {
      name: 'no-non-package-json',
      severity: 'error',
      comment:
        "This module depends on an npm package that isn't in its package.json, so it only works by accident of hoisting. Add it to the package's dependencies.",
      from: {},
      to: { dependencyTypes: ['npm-no-pkg', 'npm-unknown'] },
    },
    {
      name: 'no-duplicate-dep-types',
      severity: 'error',
      comment:
        'This package is listed in more than one dependency section of package.json. Keep it in one.',
      from: {},
      to: {
        moreThanOneDependencyType: true,
        dependencyTypesNot: ['type-only'],
      },
    },

    // Packages: tool <- calculator, store <- agent <- client, api
    layer({
      name: 'tool-is-a-leaf',
      comment:
        'tool defines what a tool is; it knows no calculator, store or agent.',
      from: { path: '^packages/tool/src/' },
      to: { path: '^(packages/(?!tool/)|api/)' },
    }),
    layer({
      name: 'calculator-and-store-only-use-tool',
      comment:
        'The calculator and the demo store are independent domains: each may use tool, never the other, the agent or the client.',
      from: { path: '^packages/(calculator|store)/src/' },
      to: { path: '^(packages/(?!(tool|$1)/)|api/)' },
    }),
    layer({
      name: 'agent-below-client-and-api',
      comment:
        'The agent (Robospresso) is used by the client and the api; it never reaches up into them.',
      from: { path: '^packages/agent/src/' },
      to: { path: '^(packages/client/|api/)' },
    }),
    layer({
      name: 'api-only-uses-agent',
      comment:
        'The Vercel Functions in api/ are thin shells over the agent; domain logic belongs in a package.',
      from: { path: '^api/' },
      to: { path: '^packages/(?!agent/)' },
    }),
    layer({
      name: 'nothing-imports-client-or-api',
      comment: 'The client and api/ are entry points, not libraries.',
      from: { pathNot: '^(packages/client/|api/)' },
      to: { path: '^(packages/client/|api/)' },
    }),
    layer({
      name: 'client-reaches-agent-via-contract',
      comment:
        'The client may only import @espressionism/agent/contract, never the agent root: the contract is Zod and types, the root is server code that must stay out of the browser bundle.',
      from: { path: CLIENT },
      to: {
        path: '^packages/agent/',
        pathNot: '^packages/agent/src/contract\\.ts$',
      },
    }),
    layer({
      name: 'public-entries-only',
      comment:
        "Import another package through its package.json exports (src/index.ts, or the agent's contract), never a file inside it.",
      from: { path: '^(?:packages/([^/]+)|api)/' },
      to: {
        path: '^packages/[^/]+/',
        pathNot: [
          '^packages/$1/',
          '^packages/[^/]+/src/index\\.ts$',
          '^packages/agent/src/contract\\.ts$',
        ],
      },
    }),

    // Client: routes -> shell components -> features -> components/ui, lib
    layer({
      name: 'nothing-imports-routes',
      comment:
        'Routes sit on top: features read their route with getRouteApi, so only the route tree imports route files.',
      from: {
        path: CLIENT,
        pathNot: `${CLIENT}(routes/|routeTree\\.gen\\.ts$)`,
      },
      to: { path: `${CLIENT}routes/` },
    }),
    layer({
      name: 'features-below-shell-components',
      comment:
        'Shell components (site header, hero header) compose features; features only use the ui primitives.',
      from: { path: `${CLIENT}features/` },
      to: { path: `${CLIENT}components/(?!ui/)` },
    }),
    layer({
      name: 'ui-is-a-leaf',
      comment:
        'components/ui holds vendored shadcn primitives: they know nothing of the app above them.',
      from: { path: `${CLIENT}components/ui/` },
      to: { path: `${CLIENT}(?!components/ui/|lib/)` },
    }),
    layer({
      name: 'lib-is-a-leaf',
      comment: 'lib holds app-agnostic helpers: it imports no app code.',
      from: { path: `${CLIENT}lib/` },
      to: { path: `${CLIENT}(?!lib/)` },
    }),
    layer({
      name: 'base-features-never-use-domain-features',
      comment: `Base features ${BASE_FEATURES} are shared building blocks (mascots, theme, forms, WebMCP); only domain features ${DOMAIN_FEATURES} build on them, never the reverse.`,
      from: { path: `${CLIENT}features/${BASE_FEATURES}/` },
      to: { path: `${CLIENT}features/${DOMAIN_FEATURES}/` },
    }),
    layer({
      name: 'pages-only-from-routes',
      comment:
        "A feature's pages/ are mounted by its routes; other code uses the feature's components and hooks instead.",
      from: {
        path: `${CLIENT}(?:features/)?([^/]+)/`,
        pathNot: `${CLIENT}routes/`,
      },
      to: { path: `${CLIENT}features/(?!$1/)[^/]+/pages/` },
    }),
    layer({
      name: 'feature-stores-are-private',
      comment:
        "A feature's stores/ hold its internal state; other code goes through the feature's hooks.",
      from: { path: `${CLIENT}(?:features/)?([^/]+)/` },
      to: { path: `${CLIENT}features/(?!$1/)[^/]+/stores/` },
    }),
  ],
  options: {
    doNotFollow: { path: 'node_modules' },
    exclude: {
      path: '(^|/)(dist|coverage|\\.output|\\.tanstack|\\.nitro|test-results|playwright-report)/',
    },
    // See type-only imports too: the contract seam is about types as well.
    tsPreCompilationDeps: true,
    // Resolves the client's `@/` alias; other packages use none.
    tsConfig: { fileName: 'packages/client/tsconfig.json' },
    enhancedResolveOptions: {
      exportsFields: ['exports'],
      // `types` first so workspace packages resolve to their src, not dist.
      conditionNames: ['types', 'import', 'default'],
      mainFields: ['types', 'module', 'main'],
      extensions: ['.ts', '.tsx', '.mts', '.js', '.mjs', '.json'],
    },
    reporterOptions: { text: { highlightFocused: true } },
  },
}
